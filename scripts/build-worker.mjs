// For the Cloudflare dashboard's single-file editor. Wrangler users can deploy
// the module entry directly. Refresh the GitHub dashboard download with:
//   node scripts/build-worker.mjs > worker.js
import { readFile } from 'node:fs/promises';
const read = (file) => readFile(new URL('../' + file, import.meta.url), 'utf8');
const [worker, engine] = await Promise.all([read('cloudflare-worker.js'), read('assets/calc-engine.js')]);
const entry = "import './assets/calc-engine.js';";
if (!worker.startsWith(entry)) throw new Error('Worker entry changed; update the bundler.');
process.stdout.write(
  '// EGYGRILLZ DASHBOARD BUNDLE - pricing engine included\n' +
    '// Generated by scripts/build-worker.mjs - do not edit.\n{\n' +
    engine +
    '\n}\n' +
    worker.slice(entry.length) +
    '\n// END EGYGRILLZ DASHBOARD BUNDLE\n',
);
